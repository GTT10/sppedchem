SUBROUTINE JGROUPMEBDF(N,IA,JA,MAXG,NGRP,IGP,JGP,INCL,JDONE,IER,&
&NNZ)
   INTEGER N, IA, JA, MAXG, NGRP, IGP, JGP, INCL, JDONE, IER, NNZ
   DIMENSION IA(1), JA(1), IGP(1), JGP(N), INCL(N), JDONE(N)
!-----------------------------------------------------------------------------
! THIS SUNROUTINE CONSTRUCTS GROUPING OF THE COLUMN INDICES OF THE
! JACOBIAN MATRIX, USED IN THE NUMERICAL EVALUATION OF THE JACOBIAN BY
! FINITE DIFFERENCES.
!
! INPUT..
! N      = THE ORDER OF THE MATRIX.
! IA,JA  = SPARSE STRUCURE DESCRIPTORS OF THE MATRIX BY ROWS.
! MAXG   = LENGTH OF AVAILABLE STORAGE IN THE IGP ARRAY.
!
! OUTPUT..
! NGRP   = NUMBER OF GROUPS.
! JGP    = ARRAY OF LENGTH N CONTAINING THE COLUMN INDICES BY GROUPS.
! IGP    = POINTER ARRAY OF LENGTH NGRP + 1 TO THE LOCATIONS IN JGP OF
!          THE BEGINNING OF EACH GROUP.
! IER    = ERROR INDICATOR. IER = 0 IF NO ERROR OCCURRED, OR 1 IF
!          MAXG WAS INSUFFICIENT.
!
! INCL AND JDONE ARE WORKING ARRAYS OF LENGTH N.
!-----------------------------------------------------------------------------
   INTEGER I, J, K, KMIN, KMAX, NCOL, NG
!
   IER = 0
   DO 10 JK = 1,N
10 JDONE(JK) = 0
   NCOL = 1
   DO 60 NG = 1,MAXG
      IGP(NG) = NCOL
      DO 20 I = 1,N
20    INCL(I) = 0
      DO 50 J = 1,N
!...
!...  REJECT COLUMN J IF IT IS ALREADY IN A GROUP.
!...
         IF (JDONE(J) .EQ. 1) GOTO 50
         KMIN = IA(J)
         KMAX = IA(J+1) - 1
         DO 30 K = KMIN, KMAX
!...
!...  REJECT COLUMN J IF IT OVERLAPS ANY COLUMN ALREADY IN THIS GROUP.
!...
            I = JA(K)
            IF (INCL(I) .EQ. 1) GOTO 50
30       CONTINUE
!...
!...  ACCEPT COLUMN J INTO GROUP NG.
!...
         JGP(NCOL) = J
         NCOL = NCOL + 1
         JDONE(J) = 1
         DO 40 K = KMIN,KMAX
            I = JA(K)
            INCL(I) = 1
40       CONTINUE
50    CONTINUE
!...
!...  STOP IF THIS GROUP IS EMPTY (GROUPING IS COMPLETE).
!...
      IF (NCOL .EQ. IGP(NG)) GOTO 70
60 CONTINUE
!...
!...  ERROR RETURN IF NOT ALL COLUMNS WERE CHOSEN (MAXG TOO SMALL).
!...
   IF (NCOL.LE. N) GOTO 80
   NG = MAXG
70 NGRP = NG - 1
   RETURN
80 IER = 1
   RETURN
END SUBROUTINE JGROUPMEBDF
!----------------------- END OF SUBROUTINE JGROUPMEBDF  ----------------------

DOUBLE PRECISION FUNCTION DLAMCH( CMACH )
!
!  -- LAPACK auxiliary routine (version 2.0) --
!     Univ. of Tennessee, Univ. of California Berkeley, NAG Ltd.,
!     Courant Institute, Argonne National Lab, and Rice University
!     October 31, 1992
!
!     .. Scalar Arguments ..
   CHARACTER          CMACH
!     ..
!
!  Purpose
!  =======
!
!  DLAMCH determines double precision machine parameters.
!
!  Arguments
!  =========
!
!  CMACH   (input) CHARACTER*1
!          Specifies the value to be returned by DLAMCH:
!          = 'E' or 'e',   DLAMCH := eps
!          = 'S' or 's ,   DLAMCH := sfmin
!          = 'B' or 'b',   DLAMCH := base
!          = 'P' or 'p',   DLAMCH := eps*base
!          = 'N' or 'n',   DLAMCH := t
!          = 'R' or 'r',   DLAMCH := rnd
!          = 'M' or 'm',   DLAMCH := emin
!          = 'U' or 'u',   DLAMCH := rmin
!          = 'L' or 'l',   DLAMCH := emax
!          = 'O' or 'o',   DLAMCH := rmax
!
!          where
!
!          eps   = relative machine precision
!          sfmin = safe minimum, such that 1/sfmin does not overflow
!          base  = base of the machine
!          prec  = eps*base
!          t     = number of (base) digits in the mantissa
!          rnd   = 1.0 when rounding occurs in addition, 0.0 otherwise
!          emin  = minimum exponent before (gradual) underflow
!          rmin  = underflow threshold - base**(emin-1)
!          emax  = largest exponent before overflow
!          rmax  = overflow threshold  - (base**emax)*(1-eps)
!
! =====================================================================
!
!     .. Parameters ..
   DOUBLE PRECISION   ONE, ZERO
   PARAMETER          ( ONE = 1.0D+0, ZERO = 0.0D+0 )
!     ..
!     .. Local Scalars ..
   LOGICAL            FIRST, LRND
   INTEGER            BETA, IMAX, IMIN, IT
   DOUBLE PRECISION   BASE, EMAX, EMIN, EPS, PREC, RMACH, RMAX, RMIN,&
   &RND, SFMIN, SMALL, T
!     ..
!     .. External Functions ..
   LOGICAL            LSAMEBDF
   EXTERNAL           LSAMEBDF
!     ..
!     .. External Subroutines ..
   EXTERNAL           DLAMC2
!     ..
!     .. Save statement ..
   SAVE               FIRST, EPS, SFMIN, BASE, T, RND, EMIN, RMIN,&
   &EMAX, RMAX, PREC
!     ..
!     .. Data statements ..
   DATA               FIRST / .TRUE. /
!     ..
!     .. Executable Statements ..
!
   IF( FIRST ) THEN
      FIRST = .FALSE.
      CALL DLAMC2( BETA, IT, LRND, EPS, IMIN, RMIN, IMAX, RMAX )
      BASE = BETA
      T = IT
      IF( LRND ) THEN
         RND = ONE
         EPS = ( BASE**( 1-IT ) ) / 2
      ELSE
         RND = ZERO
         EPS = BASE**( 1-IT )
      END IF
      PREC = EPS*BASE
      EMIN = IMIN
      EMAX = IMAX
      SFMIN = RMIN
      SMALL = ONE / RMAX
      IF( SMALL.GE.SFMIN ) THEN
!
!           Use SMALL plus a bit, to avoid the possibility of rounding
!           causing overflow when computing  1/sfmin.
!
         SFMIN = SMALL*( ONE+EPS )
      END IF
   END IF
!
   IF( LSAMEBDF( CMACH, 'E' ) ) THEN
      RMACH = EPS
   ELSE IF( LSAMEBDF( CMACH, 'S' ) ) THEN
      RMACH = SFMIN
   ELSE IF( LSAMEBDF( CMACH, 'B' ) ) THEN
      RMACH = BASE
   ELSE IF( LSAMEBDF( CMACH, 'P' ) ) THEN
      RMACH = PREC
   ELSE IF( LSAMEBDF( CMACH, 'N' ) ) THEN
      RMACH = T
   ELSE IF( LSAMEBDF( CMACH, 'R' ) ) THEN
      RMACH = RND
   ELSE IF( LSAMEBDF( CMACH, 'M' ) ) THEN
      RMACH = EMIN
   ELSE IF( LSAMEBDF( CMACH, 'U' ) ) THEN
      RMACH = RMIN
   ELSE IF( LSAMEBDF( CMACH, 'L' ) ) THEN
      RMACH = EMAX
   ELSE IF( LSAMEBDF( CMACH, 'O' ) ) THEN
      RMACH = RMAX
   END IF
!
   DLAMCH = RMACH
   RETURN
!
!     End of DLAMCH
!
END
