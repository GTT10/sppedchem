SUBROUTINE HCHOSE(RH,H,OVRIDE)
   IMPLICIT DOUBLE PRECISION(A-H,O-Z)

   COMMON / STPSZE / HSTPSZ(2,14)
   LOGICAL OVRIDE
!
!     FIRST MOVE ALL ELEMENTS DOWN ONE PLACE
!
   IF (H.NE.HSTPSZ(2,1)) THEN
      DO 5 I=12,2,-1
         I2=I-1
         HSTPSZ(1,I)=HSTPSZ(1,I2)
5     HSTPSZ(2,I)=HSTPSZ(2,I2)
!
!          NOW INSERT VALUE OF H USED BEFORE THIS CALL
!
      HSTPSZ(1,2)=H/HSTPSZ(2,1)
      HSTPSZ(2,1)=H
   ENDIF
!
!     NOW DECIDE ON THE NEW CHANGE
!
   IF (RH.GT.1.0D+0) THEN
      OVRIDE=.FALSE.
   ELSE IF (HSTPSZ(1,2).LE.1.0D+0) THEN
      OVRIDE=.FALSE.
   ELSE IF ((RH*H).LE.HSTPSZ(2,2)) THEN
      OVRIDE=.FALSE.
   ELSE
      RH=HSTPSZ(2,2)/H
      OVRIDE=.TRUE.
   ENDIF
   HSTPSZ(1,1)=RH
   RETURN
END
!-----------------------------------------------------------------------------
!     THE NEXT ROUTINE PREFORMS PREPROCESSING RELATED TO THE SPARSE LINEAR
!     SYSTEMS.
!     THE OPERATIONS THAT ARE PERFORMED HERE ARE
!  * COMPUTE SPARSENESS STRUCTURE OF THE JACOBIAN MATRIX ACCORDING TO MF,
!  * COMPUTE GROUPING OF COLUMN INDICES (MF = 26),
!  * COMPUTE A NEW ORDERING OF ROWS AND COLUMNS OF THE MATRIX,
!  * REORDER JA CORRESPONDING TO THE NEW ORDERING,
!  * PERFORM A SYMBOLIC LU FACTORIZATION OF THE MATRIX.
!-----------------------------------------------------------------------------
!
SUBROUTINE SPARSDET(N,T,Y0,PWCOPY,SCALE,IA,JA,SAVF,P,IP,NSP,&
&ISP,RSP,NONZ,NGP,JGP,IGP,MF,INCL,JDONE,LOUT,F,PDERV,NNZ,&
&IPAR,RPAR,IERR)
!
!     ..ARRAY ARGUMENTS ..
   DOUBLE PRECISION T
   DOUBLE PRECISION PWCOPY(NONZ),Y0(N),RSP(NSP),SAVF(N),YJ
   DOUBLE PRECISION FAC,SCALE(N),FTEM(1),DQ,RPAR(*)
   INTEGER P(N),IP(N),IA(N+1),JA(NONZ),ISP(NSP), JGP(N),IGP(NONZ),&
   &INCL(N),JDONE(N),IPAR(*)
!
   LOGICAL ORDER
!     .. EXTERNAL SUBROUTINES ..
   EXTERNAL F,PDERV,ODRV,CDRV
!     ..
!     .. INTRINSIC FUNCTIONS ..
   INTRINSIC DABS,DMAX1
!     ..
!     .. COMMON BLOCKS ..
   COMMON /ORDERING/ORDER
!...
!...  PERTURB THE INITIAL CONDITIONS, Y0, FOR STRUCTURE DETERMINATION.
!...
   DO I=1,N
      FAC= 1.0D0+1.0D0/(DFLOAT(I)+1.D0)
      Y0(I) =Y0(I) +FAC*DSIGN(SCALE(I),Y0(I))
   ENDDO
!...
!...  COMPUTE THE SPARSITY STRUCTURE FROM THE USER SUPPLIES JACOBIAN
!...  ROUTINE PDERV.
!...
   IF (MF .EQ. 25) THEN
      KK = 1
      IA(1) =1
      DO 111 J =1,N
         JA(KK) = J
         KK = KK+ 1
         DO K=1,N
            SAVF(K) = 0.0D0
         ENDDO
         CALL PDERV(N,T,Y0,J,SAVF,IPAR,RPAR,IERR)
         DO 112 II=1,N
            IF (DABS(SAVF(II)) .LE. 0.0D0 ) GOTO 112
            IF (II .EQ. J) GOTO 112
            JA(KK) = II
            KK=KK+1
112      CONTINUE
         IA(1+J) = KK
111   CONTINUE
   ELSE
!....
!.... MF = 26  COMPUTE SPARSITY STRUCTURE FROM RESULTS OF N+1 CALLS TO F
!....
100   KK = 1
      IA(1) = 1
      CALL F(N,T,Y0,SAVF,IPAR,RPAR,IERR)
      DO 120 J = 1,N
         JA(KK) = J
         KK = KK + 1
         YJ = Y0(J)
         DYJ = DSIGN(SCALE(J),YJ)
         Y0(J) = YJ + DYJ
         CALL F(N,T,Y0,PWCOPY,IPAR,RPAR,IERR)
         Y0(J) = YJ
         DO 110 II = 1,N
            DQ = (PWCOPY(II) - SAVF(II))/DYJ
            IF (DABS(DQ) .LE. 0.D0) GOTO 110
            IF (II .EQ. J) GOTO 110
            JA(KK) = II
            KK = KK + 1
110      CONTINUE
         IA(1+J) = KK
120   CONTINUE
   ENDIF
!.....
   NNZ = IA(1+N)-1
   IF (NNZ .GT. NONZ) THEN
      WRITE(LOUT,*) 'NUMBER OF NONZEROS ',NNZ, 'NOT',NONZ
      STOP
   ENDIF
!....
!.... COMPUTE COLUMN GROUPING FOR SPARSE NUMERICAL JACOBIAN I.E. MF = 26
!....
   IF ( MF .EQ. 26) THEN
      MAXG = N+1
      CALL JGROUPMEBDF(N,IA,JA,MAXG,NGP,IGP,JGP,INCL,JDONE,IER,NNZ)
   ENDIF
!....
!.... COMPUTE NEW ORDERING OF NONZERO  ENTERIS IN THE ITERATION MATRIX
!....
   DO I=1,N
      P(I) = I
   ENDDO
   CALL ODRV(N,IA,JA,PWCOPY,P,IP,NSP,ISP,1,IFLAG)
   IF (IFLAG .NE. 0) THEN
      WRITE(LOUT,*)'FATAL ERROR IN THE ODRV ROUTINE (SPARSE ORDERING)&
      &        IFALG RETURN IS= ',IFLAG
      STOP
   ENDIF
!....
!.... REORDER AND DO SYMBOLIC LU FACTORIZATION OF THE ITERATION MATRIX
!....
   DO I=1, NNZ
      PWCOPY(I) =0.0D0
   ENDDO
   CALL CDRV(N,P,P,IP,IA,JA,PWCOPY,FTEM,FTEM,NSP,ISP,&
   &RSP,IEXTRA,5,IFLAG)
   IF (IFLAG .EQ. 0) THEN
      ORDER = .TRUE.
   ELSE
      WRITE(LOUT,1111) IFLAG
1111  FORMAT('FATAL ERROR IN THE CDRV ROUTINE (SYMBOLIC&
      &        FACTORIZATION) IFLAG RETURN IS ', I3)
      STOP
   ENDIF
!
   RETURN
END
