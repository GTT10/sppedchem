SUBROUTINE PRDICT(T,H,Y,L,N,YPRIME,NFE,F,IPAR,RPAR,IERR)

   IMPLICIT DOUBLE PRECISION(A-H,O-Z)
! **********************************************************************
!     PREDICTS A VALUE FOR Y AT (T+H) GIVEN THE HISTORY ARRAY AT T
!     THEN EVALUATES THE DERIVATIVE AT THIS POINT, THE RESULT OF THIS
!     EVALUATION BEING STORED IN YPRIME()
! **********************************************************************

!     .. SCALAR ARGUMENTS ..
   INTEGER L,N
!     ..
!     .. ARRAY ARGUMENTS ..
   DIMENSION  Y(N,12),YPRIME(N),IPAR(*),RPAR(*)
!     ..
!     .. LOCAL SCALARS ..
   INTEGER I,J2
!     ..
!     .. EXTERNAL SUBROUTINES ..
   EXTERNAL F
!     ..
!     .. COMMON BLOCKS ..
   INTEGER NFE
!     ..
   DO 20 J2 = 2,L
      DO 10 I = 1,N
         Y(I,1) = Y(I,1) + Y(I,J2)
10    CONTINUE
20 CONTINUE
   T = T + H
   CALL F(N,T,Y,YPRIME,IPAR,RPAR,IERR)
   NFE = NFE + 1
   RETURN
END

