SUBROUTINE INTERPMEBDF(N,JSTART,H,T,Y,TOUT,Y0)

   IMPLICIT DOUBLE PRECISION(A-H,O-Z)
!     .. SCALAR ARGUMENTS ..
   INTEGER JSTART,N
!     ..
!     .. ARRAY ARGUMENTS ..
   DIMENSION  Y(N,12),Y0(N)
!     ..
!     .. LOCAL SCALARS ..
   INTEGER I,J,L
!     ..
!     .. INTRINSIC FUNCTIONS ..
!     ..
   DO 10 I = 1,N
      Y0(I) = Y(I,1)
10 CONTINUE
   L = JSTART + 2
   S = (TOUT-T)/H
   S1 = 1.0D+0
   DO 30 J = 2,L
      S1 = S1* (S+DBLE(FLOAT(J-2)))/DBLE(FLOAT(J-1))
      DO 20 I = 1,N
         Y0(I) = Y0(I) + S1*Y(I,J)
20    CONTINUE
30 CONTINUE
   RETURN
! -------------- END OF SUBROUTINE INTERP ---------------------------
END SUBROUTINE INTERPMEBDF
