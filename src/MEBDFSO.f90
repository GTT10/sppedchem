!
SUBROUTINE PSET(Y,N,H,T,UROUND,EPSJAC,CON,MITER,IER,F,PDERV,&
&NRENEW,YMAX,SAVE1,SAVE2,PW,PWCOPY,WRKSPC,ITOL,RTOL,ATOL,&
&NPSET,NJE,NFE,NDEC,RSP,IA,JA,P,IP,NSP,ISP,NONZ,SAVF,NGRP,&
&JGP,IGP,LOUT,IPAR,RPAR,IERR)

   IMPLICIT DOUBLE PRECISION(A-H,O-Z)
! -------------------------------------------------------------------
!     PSET IS CALLED BY STIFF TO COMPUTE AND PROCESS THE MATRIX
!     I/(H*EL(1)) - J  WHERE J IS AN APPROXIMATION TO THE RELEVANT JACOBIAN
!     AND I IS THE IDENTITY MATRIX.  THIS MATRIX IS THEN SUBJECTED TO LU
!     DECOMPOSITION IN PREPARATION FOR LATER SOLUTION OF LINEAR SYSTEMS
!     OF ALGEBRAIC EQUATIONS WITH LU AS THE COEFFICIENT MATRIX.
!     IN ADDITION TO VARIABLES DESCRIBED PREVIOUSLY, COMMUNICATION WITH
!     PSET USES THE FOLLOWING ..
!     EPSJAC = DSQRT(UROUND), USED IN NUMERICAL JACOBIAN INCREMENTS.
! *******************************************************************
!     THE ARGUMENT NRENEW IS USED TO SIGNAL WHETHER OR NOT
!     WE REQUIRE A NEW JACOBIAN TO BE CALCULATED.
!
!        IF NRENEW > 0 THEN WE REQUIRE A NEW J TO BE COMPUTED
!                  = 0 THEN USE A COPY OF THE LAST J COMPUTED
! *******************************************************************
!    THE FLAG IER IS SET TO 1 WHEN A STRUCTURAL SINGULARITY OCCURS
!    AND TO 2 WHEN A NUMERICAL SINGULARITY OCCURS
! *******************************************************************
!
!     .. SCALAR ARGUMENTS ..
   INTEGER IER,MITER,N,NRENEW
!     ..
!     .. ARRAY ARGUMENTS ..
   DIMENSION  PW(*),PWCOPY(*),SAVE2(N),WRKSPC(N),Y(N,12),&
   &YMAX(N),SAVE1(N),RTOL(1),ATOL(1),RSP(NSP),FTEM(1),SAVF(N),&
   &IPAR(*),RPAR(*)
   INTEGER P(N),IP(N),IA(N+1),JA(NONZ),ISP(NSP),IGP(NGRP+1),JGP(N)
!
   LOGICAL ORDER
!     .. EXTERNAL SUBROUTINES ..
   EXTERNAL F,PDERV,ODRV,CDRV
!     ..
!     .. INTRINSIC FUNCTIONS ..
   INTRINSIC DABS,DMAX1,DSQRT
!     ..
!     .. COMMON BLOCKS ..
   COMMON /ORDERING/ORDER
   INTEGER MAXORD,NBSOL,NCOSET,NDEC,NFE,NJE,NPSET,NQUSED,NSTEP
!
!
   NPSET = NPSET + 1
   IF (NRENEW.EQ.0) THEN
      IF (MITER.EQ.5 .OR. MITER .EQ. 6) THEN
         KK=1
         KMIN = IA(1)
         DO 275 J=1,N
            KMAX=IA(1+J)-1
            DO 270 K=KMIN,KMAX
               I =JA(K)
               PIJ=-PWCOPY(K)
               IF ( I .EQ. J) PIJ = PIJ +1.0D0/CON
               PW(K) = PIJ
270         CONTINUE
            KMIN=KMAX+1
275      CONTINUE
      ENDIF
      GO TO 131
   ENDIF
   NJE = NJE + 1
70 CONTINUE
!
!.... FORM THE ITERATION MATRIX P =I/CON - J
!.... MITER = 5, CALL PDERV ROUTINE AND FORM P
!...
   IF (MITER .EQ. 5) THEN
      KMIN = IA(1)
      DO 130 J = 1,N
         KMAX = IA(1+J) -1
         DO 110 I = 1,N
110      PWCOPY(I) = 0.0D0
         CALL PDERV(N,T,Y,J,PWCOPY,IPAR,RPAR,IERR)
         DO 120 K = KMIN,KMAX
            II = JA(K)
            PW(K) = -PWCOPY(II)
            IF (II .EQ. J) PW(K) = PW(K) + 1.0D0/CON
120      CONTINUE
         KMIN = KMAX + 1
130   CONTINUE
   ELSE
!....
!.... NUMERICAL APRROXIMATION TO THE SPARSE JACOBIAN, MAKE NGRP CALS
!.... TO F TO APPROXIMATE THE JACOBIAN AND FORM THE MATRIX P
!....
      DO 35 I=1,N
         IF(ITOL.EQ.2) THEN
            YMAX(I)=dabs(Y(I,1))*RTOL(1)+ATOL(1)
         ELSE IF (ITOL.EQ.3) THEN
            YMAX(I)=dabs(Y(I,1))*RTOL(1)+ATOL(I)
         ELSE IF(ITOL.EQ.4) THEN
            YMAX(I)=dabs(Y(I,1))*RTOL(I)+ATOL(1)
         ELSE IF(ITOL.EQ.5) THEN
            YMAX(I)=dabs(Y(I,1))*RTOL(I)+ATOL(I)
         END IF
35    CONTINUE
      D = 0.D0
      DO 41 I = 1,N
         D = D + (SAVE2(I)*YMAX(I))**2
41    CONTINUE
      IF (ITOL .EQ. 1) D= D*RTOL(1)**2
      D = DSQRT(D/DFLOAT(N))
      R0 = DABS(H)*D*(1.0D+03)*UROUND*DFLOAT(N)
      IF (R0.EQ.0.D0) R0 = 1.D0
      JMIN = IGP(1)
      DO 240 NG =1,NGRP
         JMAX= IGP(1+NG)-1
         DO 210 J=JMIN, JMAX
            JJ= JGP(J)
            SAVE1(JJ) =Y(JJ,1)
            YI = Y(JJ,1)
            R = DMAX1(EPSJAC*DABS(YI),R0/YMAX(JJ))
210      Y(JJ,1)=Y(JJ,1)+R
         CALL F(N,T,Y,WRKSPC,IPAR,RPAR,IERR)
         DO 230 J=JMIN,JMAX
            JJ = JGP(J)
            Y(JJ,1)=SAVE1(JJ)
            YJJ = Y(JJ,1)
            R = DMAX1(EPSJAC*DABS(YJJ),R0/YMAX(JJ))
            D = CON/R
            K1 = IA(JJ)
            K2 = IA(JJ+1) -1
            DO 220 K=K1,K2
               I = JA(K)
               TEMPRY = WRKSPC(I) - SAVE2(I)
               PWCOPY(k)=TEMPRY/R
               PW(k) = -PWCOPY(k)
               IF (I .EQ. JJ ) PW(K) = PW(K) + 1.0D0/CON
220         CONTINUE
230      CONTINUE
         JMIN = JMAX + 1
240   CONTINUE
      NFE = NFE + NGRP
   ENDIF
131 CONTINUE
!....
!.... NUMERICAL FACTORIZATION OF THE ITERATION MATRIX P
!....
   DO 132 I=1,N
132 WRKSPC(I) = 0.0D0
   CALL CDRV(N,P,P,IP,IA,JA,PW,WRKSPC,WRKSPC,NSP,ISP,&
   &RSP,IEXTRA,2,IFLAG)
!
   IF (IFLAG .NE. 0) THEN
      WRITE(LOUT,1333) IFLAG
1333  FORMAT('FATAL ERROR IN THE CDRV ROUTINE (SPARSE&
      &        NUMERICAL FACTORIZATION) IFLAG RETURN IS ',I3)
      IER = 1
      ORDER = .FALSE.
   ENDIF
   NDEC = NDEC + 1
!
   RETURN
END
! ---------------------- END OF SUBROUTINE PSET ---------------------

SUBROUTINE ERRORS(N,TQ,EDN,E,EUP,BND,EDDN)

   IMPLICIT DOUBLE PRECISION(A-H,O-Z)
!     ***************************************************
!
!     THIS ROUTINE CALCULATES ERRORS USED IN TESTS
!     IN STIFF .
!
!     ***************************************************
!     .. SCALAR ARGUMENTS ..
   INTEGER N
!     ..
!     .. ARRAY ARGUMENTS ..
   DIMENSION  TQ(5)
!     ..
!     .. LOCAL SCALARS ..
!     ..
!     .. INTRINSIC FUNCTIONS ..
!     ..
   SQHOL = DBLE(FLOAT(N))
   EDN = TQ(1)*TQ(1)*SQHOL
!
!     ** ERROR ASSOCIATED WITH  METHOD OF ORDER ONE LOWER.
!
   E = TQ(2)*TQ(2)*SQHOL
!
!     ** ERROR ASSOCIATED WITH PRESENT ORDER
!
   EUP = TQ(3)*TQ(3)*SQHOL
!
!     ** ERROR ASSOCIATED WITH HIGHER ORDER METHOD
!
   BND = TQ(4)*TQ(4)*SQHOL*0.5D+0

   EDDN=TQ(5)*TQ(5)*SQHOL
!
!     ** ERROR ASSOCIATED WITH METHOD OF ORDER TWO LOWER.
   RETURN
END
